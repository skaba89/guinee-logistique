// Types
export type ShipmentType = 'aerien' | 'maritime' | 'terrestre';
export type ShipmentStatus = 'en_attente' | 'confirmee' | 'en_transit' | 'livree' | 'retardee' | 'annulee';
export type ClientType = 'entreprise' | 'particulier';
export type InvoiceStatus = 'payee' | 'en_attente' | 'en_retard' | 'annulee';
export type VehicleType = 'camion' | 'fourgon' | 'remorque';
export type VehicleStatus = 'actif' | 'en_maintenance' | 'hors_service';

export interface User {
  id: string;
  phone: string;
  password: string;
  name: string;
  role: string;
  email: string;
  avatar?: string;
}

export interface Shipment {
  id: string;
  trackingNumber: string;
  type: ShipmentType;
  status: ShipmentStatus;
  origin: string;
  destination: string;
  clientName: string;
  clientPhone: string;
  weight: number;
  dimensions: string;
  dateCreation: string;
  dateExpedition: string;
  dateLivraisonEstimee: string;
  price: number;
  notes: string;
  driverName: string;
}

export interface Client {
  id: string;
  name: string;
  phone: string;
  email: string;
  address: string;
  city: string;
  type: ClientType;
  totalShipments: number;
  totalRevenue: number;
}

export interface Invoice {
  id: string;
  invoiceNumber: string;
  clientName: string;
  amount: number;
  status: InvoiceStatus;
  dateEmission: string;
  dateEcheance: string;
  shipments: string[];
}

export interface Vehicle {
  id: string;
  immatriculation: string;
  type: VehicleType;
  marque: string;
  modele: string;
  annee: number;
  status: VehicleStatus;
  driverName: string;
  driverPhone: string;
  capacity: number;
  kilometrage: number;
}

export interface DashboardStats {
  totalShipments: number;
  shipmentsByType: { type: ShipmentType; count: number }[];
  shipmentsByStatus: { status: ShipmentStatus; count: number }[];
  revenue: { month: string; amount: number }[];
  activeVehicles: number;
  clientsCount: number;
}

// Container for maritime
export interface Container {
  id: string;
  containerNumber: string;
  type: '20ft' | '40ft' | '40ft_hc' | 'reefer';
  status: 'empty' | 'loaded' | 'in_transit' | 'at_port' | 'delivered';
  vesselName: string;
  voyageNumber: string;
  portOfLoading: string;
  portOfDischarge: string;
  eta: string;
  weight: number;
  bookingRef: string;
  blNumber: string;
  clientName: string;
}

// Flight for air freight
export interface Flight {
  id: string;
  flightNumber: string;
  airline: string;
  origin: string;
  destination: string;
  departureTime: string;
  arrivalTime: string;
  status: 'scheduled' | 'boarding' | 'in_flight' | 'landed' | 'delayed' | 'cancelled';
  awbPrefix: string;
  awbNumber: string;
  capacity: number;
  booked: number;
  clientName: string;
}

// Route for ground transport
export interface Route {
  id: string;
  routeNumber: string;
  origin: string;
  destination: string;
  distance: number;
  estimatedDuration: string;
  driverName: string;
  vehiclePlate: string;
  status: 'planned' | 'in_progress' | 'completed' | 'delayed';
  departureTime: string;
  arrivalTime: string;
  stops: string[];
  cargo: string;
  clientName: string;
}

// Parcel
